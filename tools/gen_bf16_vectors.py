"""Generate packages/bf16/vectors.zig: F32 bit patterns and their BF16 bits from PyTorch.

Usage:
    python3 -I tools/gen_bf16_vectors.py OUTPUT.zig

The vectors are the reference for the bf16 package. Edge cases come first, then
random bit patterns from a fixed seed. Requires torch; the output records its version.
"""

import random
import sys

import torch

EdgeCases = [
    0x00000000, 0x80000000,  # +0, -0
    0x00000001, 0x80000001,  # smallest subnormals
    0x007FFFFF, 0x00800000,  # largest subnormal, smallest normal
    0x3F800000, 0xBF800000,  # 1.0, -1.0
    0x3DCCCCCD,              # 0.1 (f32), rounds up to 0x3DCD
    0x3F808000, 0x3F818000,  # exact ties: round to the even mantissa
    0x3F807FFF, 0x3F817FFF,  # just below the tie
    0x40490FDB,              # pi
    0x7F7FFFFF, 0xFF7FFFFF,  # largest finite values, round up to infinity
    0x7F800000, 0xFF800000,  # +inf, -inf
    0x7FC00000, 0x7FC00001,  # quiet NaN, NaN with payload
    0xFFC00000, 0xFF800001,  # negative quiet NaN, signalling NaN
    0x7F800001,              # signalling NaN with the sign bit clear
]
RandomCount = 4096
Seed = 20260626


def as_signed32(bits):
    return bits - (1 << 32) if bits >= (1 << 31) else bits


def main(argv):
    if len(argv) != 2:
        print(__doc__, file=sys.stderr)
        return 2
    output = argv[1]
    rng = random.Random(Seed)
    inputs = EdgeCases + [rng.getrandbits(32) for _ in range(RandomCount)]
    floats = torch.tensor([as_signed32(bits) for bits in inputs], dtype=torch.int32).view(torch.float32)
    bf16_bits = floats.to(torch.bfloat16).view(torch.int16).tolist()
    lines = [
        "//",
        "// Ko, (Baczynski-Bruce) 2026; Apache 2.0",
        "//",
        "//! Generated by tools/gen_bf16_vectors.py. Do not edit by hand.",
        f"//! Reference: PyTorch {torch.__version__}, float32 to bfloat16 conversion.",
        "",
        "/// Pairs of (F32 bit pattern, BF16 bit pattern produced by PyTorch).",
        "pub const Pairs = [_][2]u32{",
    ]
    for bits, expected in zip(inputs, bf16_bits):
        lines.append(f"    .{{ 0x{bits:08X}, 0x{expected & 0xFFFF:04X} }},")
    lines += ["};", ""]
    with open(output, "w", encoding="utf-8") as handle:
        handle.write("\n".join(lines))
    print(f"wrote {len(inputs)} vectors from torch {torch.__version__} to {output}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
