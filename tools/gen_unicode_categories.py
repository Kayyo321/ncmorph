"""Generate packages/unicode_categories/tables.zig from UnicodeData.txt.

Usage:
    python3 -I tools/gen_unicode_categories.py UnicodeData.txt OUTPUT.zig UNICODE_VERSION

UnicodeData.txt is part of the Unicode Character Database, distributed under the
UNICODE LICENSE V3 (https://www.unicode.org/license.txt). The generated file records
the Unicode version and the source file.
"""

import sys
import hashlib

MaxCodePoint = 0x10FFFF
Categories = [
    "Lu", "Ll", "Lt", "Lm", "Lo",
    "Mn", "Mc", "Me",
    "Nd", "Nl", "No",
    "Pc", "Pd", "Ps", "Pe", "Pi", "Pf", "Po",
    "Sm", "Sc", "Sk", "So",
    "Zs", "Zl", "Zp",
    "Cc", "Cf", "Cs", "Co", "Cn",
]
Unicode16Sha256 = "ff58e5823bd095166564a006e47d111130813dcf8bf234ef79fa51a870edb48f"
Unicode16Size = 2175362


def read_entries(path):
    """Return (first, last, category) for every entry in UnicodeData.txt."""
    entries = []
    range_start = None
    with open(path, encoding="utf-8") as handle:
        for line in handle:
            fields = line.rstrip("\n").split(";")
            if len(fields) < 3 or not fields[0]:
                continue
            code_point = int(fields[0], 16)
            name, category = fields[1], fields[2]
            if name.endswith(", First>"):
                range_start = code_point
            elif name.endswith(", Last>"):
                if range_start is None:
                    raise ValueError(f"range end without a start at U+{code_point:04X}")
                entries.append((range_start, code_point, category))
                range_start = None
            else:
                entries.append((code_point, code_point, category))
    if range_start is not None:
        raise ValueError("UnicodeData.txt ends inside a range")
    return entries


def verify_source(path, version):
    """Reject a Unicode 16 source other than the pinned UnicodeData.txt."""
    if version != "16.0.0":
        return None
    with open(path, "rb") as handle:
        content = handle.read()
    digest = hashlib.sha256(content).hexdigest()
    if len(content) != Unicode16Size or digest != Unicode16Sha256:
        raise ValueError(
            "Unicode 16.0.0 source mismatch: expected "
            f"{Unicode16Size} bytes with SHA-256 {Unicode16Sha256}, got "
            f"{len(content)} bytes with SHA-256 {digest}"
        )
    return digest


def build_runs(entries):
    """Cover 0..MaxCodePoint with runs of one category. Unlisted code points are Cn."""
    runs = []
    cursor = 0
    for first, last, category in sorted(entries):
        if first < cursor:
            raise ValueError(f"overlapping entry at U+{first:04X}")
        if first > cursor:
            runs.append([cursor, first - 1, "Cn"])
        runs.append([first, last, category])
        cursor = last + 1
    if cursor <= MaxCodePoint:
        runs.append([cursor, MaxCodePoint, "Cn"])
    merged = []
    for first, last, category in runs:
        if category not in Categories:
            raise ValueError(f"unknown general category {category}")
        if merged and merged[-1][2] == category and merged[-1][1] + 1 == first:
            merged[-1][1] = last
        else:
            merged.append([first, last, category])
    return merged


def render(runs, version, source_sha256):
    lines = [
        "//",
        "// Ko, (Baczynski-Bruce) 2026; Apache 2.0",
        "//",
        "//! Generated Unicode general-category ranges. Do not edit by hand.",
        "//!",
        f"//! Generated by tools/gen_unicode_categories.py from UnicodeData.txt, Unicode {version}.",
        "//! UnicodeData.txt is distributed under the UNICODE LICENSE V3 (https://www.unicode.org/license.txt).",
        f"//! UnicodeData.txt SHA-256: {source_sha256}." if source_sha256 else "",
        "",
        f'pub const Version = "{version}";',
        "",
        "pub const Category = enum {",
    ]
    lines += [f"    {category}," for category in Categories]
    lines += [
        "};",
        "",
        "pub const range_t = struct { first: u21, last: u21, category: Category };",
        "",
        "/// Sorted, contiguous ranges covering every code point from 0 to 0x10FFFF.",
        "pub const Ranges = [_]range_t{",
    ]
    for first, last, category in runs:
        lines.append(f"    .{{ .first = 0x{first:06X}, .last = 0x{last:06X}, .category = .{category} }},")
    lines.append("};")
    lines.append("")
    return "\n".join(lines)


def main(argv):
    if len(argv) != 4:
        print(__doc__, file=sys.stderr)
        return 2
    source, output, version = argv[1], argv[2], argv[3]
    source_sha256 = verify_source(source, version)
    runs = build_runs(read_entries(source))
    if source_sha256:
        verify_complete_coverage(runs)
    with open(output, "w", encoding="utf-8") as handle:
        handle.write(render(runs, version, source_sha256))
    print(f"wrote {len(runs)} ranges for Unicode {version} to {output}")
    return 0


def verify_complete_coverage(runs):
    """Test that the generated runs are ordered and cover the Unicode domain."""
    if not runs or runs[0][0] != 0 or runs[-1][1] != MaxCodePoint:
        raise ValueError("generated ranges do not cover 0..0x10FFFF")
    for previous, current in zip(runs, runs[1:]):
        if previous[1] + 1 != current[0]:
            raise ValueError(f"generated ranges have a gap at U+{previous[1] + 1:04X}")


if __name__ == "__main__":
    sys.exit(main(sys.argv))
