"""Generate NFC lookup tables from the pinned Unicode 9.0.0 data files."""

import argparse
import hashlib
from pathlib import Path
import re

UNICODE_SHA256 = "68dfc414d28257b9b5d6ddbb8b466c768c00ebdf6cbf7784364a9b6cad55ee8f"
EXCLUSIONS_SHA256 = "5623df16856ad4007c60bdfff6f054e087521becd24cb4006be69c3a1d851aee"


def verified_bytes(path: Path, expected: str) -> bytes:
    data = path.read_bytes()
    actual = hashlib.sha256(data).hexdigest()
    if actual != expected:
        raise ValueError(f"{path}: expected SHA-256 {expected}, got {actual}")
    return data


def read_exclusions(data: bytes) -> set[int]:
    result = set()
    for line in data.decode("utf-8").splitlines():
        match = re.match(r"^\s*#?\s*([0-9A-Fa-f]{4,6})(?:\s|$)", line)
        if match:
            result.add(int(match.group(1), 16))
    return result


def read_unicode_data(data: bytes):
    decompositions = {}
    combining_classes = {}
    for line in data.decode("ascii").splitlines():
        fields = line.split(";")
        codepoint = int(fields[0], 16)
        combining = int(fields[3])
        decomposition = fields[5]
        # UnicodeData's First/Last records do not define decomposition mappings.
        if combining:
            combining_classes[codepoint] = combining
        if decomposition and not decomposition.startswith("<"):
            decompositions[codepoint] = tuple(int(item, 16) for item in decomposition.split())
    return decompositions, combining_classes


def ranges_for(values):
    ranges = []
    for codepoint, value in sorted(values.items()):
        if ranges and ranges[-1][1] + 1 == codepoint and ranges[-1][2] == value:
            ranges[-1] = (ranges[-1][0], codepoint, value)
        else:
            ranges.append((codepoint, codepoint, value))
    return ranges


def zig_table(unicode_path: Path, exclusions_path: Path) -> str:
    unicode_data = verified_bytes(unicode_path, UNICODE_SHA256)
    exclusion_data = verified_bytes(exclusions_path, EXCLUSIONS_SHA256)
    decompositions, combining_classes = read_unicode_data(unicode_data)
    exclusions = read_exclusions(exclusion_data)

    flat_decomposition = []
    decomposition_rows = []
    for codepoint, mapping in sorted(decompositions.items()):
        offset = len(flat_decomposition)
        flat_decomposition.extend(mapping)
        decomposition_rows.append((codepoint, offset, len(mapping)))

    composition_rows = []
    for codepoint, mapping in decompositions.items():
        if len(mapping) == 2 and codepoint not in exclusions:
            composition_rows.append((mapping[0], mapping[1], codepoint))
    composition_rows.sort()

    lines = [
        "//",
        "// Ko, (Baczynski-Bruce) 2026; Apache 2.0",
        "//",
        "//! Generated Unicode 9.0.0 canonical normalization tables. Do not edit by hand.",
        "//! Generated by tools/gen_nfc_tables.py from the pinned Unicode 9.0.0 files.",
        f"//! UnicodeData.txt SHA-256: {UNICODE_SHA256}.",
        f"//! CompositionExclusions.txt SHA-256: {EXCLUSIONS_SHA256}.",
        "",
        'pub const Version = "9.0.0";',
        "pub const decomposition_t = struct { codepoint: u21, offset: u16, len: u8 };",
        "pub const composition_t = struct { first: u21, second: u21, composed: u21 };",
        "pub const ccc_range_t = struct { first: u21, last: u21, value: u8 };",
        "",
        "pub const DecompositionData = [_]u21{",
    ]
    for start in range(0, len(flat_decomposition), 12):
        lines.append("    " + ", ".join(f"0x{cp:06X}" for cp in flat_decomposition[start : start + 12]) + ",")
    lines.extend(["};", "", "pub const Decompositions = [_]decomposition_t{"])
    lines.extend(f"    .{{ .codepoint = 0x{cp:06X}, .offset = {offset}, .len = {length} }}," for cp, offset, length in decomposition_rows)
    lines.extend(["};", "", "pub const Compositions = [_]composition_t{"])
    lines.extend(f"    .{{ .first = 0x{first:06X}, .second = 0x{second:06X}, .composed = 0x{composed:06X} }}," for first, second, composed in composition_rows)
    lines.extend(["};", "", "pub const CombiningClassRanges = [_]ccc_range_t{"])
    lines.extend(f"    .{{ .first = 0x{first:06X}, .last = 0x{last:06X}, .value = {value} }}," for first, last, value in ranges_for(combining_classes))
    lines.extend(["};", ""])
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("unicode_data", type=Path)
    parser.add_argument("composition_exclusions", type=Path)
    parser.add_argument("output", type=Path)
    args = parser.parse_args()
    args.output.write_text(zig_table(args.unicode_data, args.composition_exclusions), encoding="utf-8")


if __name__ == "__main__":
    main()
